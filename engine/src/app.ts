export async function buildApp(store=new Store(process.env.DATABASE_PATH||'data/engine.sqlite'),options:{workers?:boolean}={}){
  const app=Fastify({logger:false,bodyLimit:2*1024*1024,trustProxy:process.env.TRUST_PROXY==='true'});
  // onClose is LIFO: register database ownership first so every worker drains before it.
  app.addHook('onClose',async()=>{store.close();});
  const origins=(process.env.ALLOWED_ORIGINS||'http://localhost:5173,http://127.0.0.1:5173,http://localhost:3000,http://127.0.0.1:3000,http://127.0.0.1:4310,http://localhost:4310').split(',');
  await app.register(cookie);
  await app.register(cors,{origin:origins,credentials:true});
  await app.register(rateLimit,{max:Number(process.env.RATE_LIMIT_MAX||600),timeWindow:'1 minute',allowList:(req)=>!req.url.startsWith('/api/')&&!req.url.startsWith('/widget/')});
  app.addHook('onRequest',async(req,reply)=>{
    reply.header('X-Content-Type-Options','nosniff').header('Referrer-Policy','no-referrer').header('Cache-Control','no-store');
    const publicPath=PUBLIC_CHAT_PATHS.has(req.url.split('?')[0])||PUBLIC_BOOKING_PATHS.has(req.url.split('?')[0]);
    if(!publicPath&&['POST','PATCH','PUT','DELETE'].includes(req.method)&&req.headers.origin&&!origins.includes(req.headers.origin))return reply.code(403).send({error:{code:'origin_rejected',message:'Origem não autorizada.'}});
  });
  app.setErrorHandler((error,req,reply)=>{
    if(error instanceof ZodError)return reply.code(400).send({error:{code:'validation_error',message:'Dados inválidos.',fields:error.issues.map(i=>({path:i.path.join('.'),code:i.code}))}});
    const e=error as {statusCode?:number;code?:string;message?:string};
    const status=e.statusCode&&e.statusCode>=400&&e.statusCode<500?e.statusCode:500;
    return reply.code(status).send({error:{code:status===500?'internal_error':e.code||'request_error',message:status===500?'Falha interna.':e.message||'Requisição inválida.'}});
  });
  await registerAuth(app,store);
  await registerAccountProfile(app,store);
  await registerOnboardingEditorState(app,store);
  const recovery=await registerAuthRecovery(app,store,{workers:options.workers});
  await registerAuthRecoveryUI(app);
  app.get('/health',async()=>({status:'ok',service:'kloel-engine',version:'0.1.0',environment:process.env.NODE_ENV==='production'?'production':'local',productionReady:process.env.NODE_ENV==='production'}));
  await registerCRM(app,store);
  registerContactBlocks(app,store);
  registerCompanySlug(app,store);
  registerWebchatHosted(app,store);
  registerChatEnd(app,store);
  registerIntegrationRequests(app,store);
  registerCreditClaims(app,store);
  const crmCapture=await registerCRMCapture(app,store);
  await registerDomains(app,store);
  await registerAgentEditorState(app,store);
  await registerWebchatChannels(app,store);
  await registerPhoneConfig(app,store);
  await registerWhatsAppChannels(app,store);
  await registerConversationControl(app,store);
  await registerConversationEditorState(app,store);
  await registerConversationSearch(app,store);
  const analysis=await registerConversationAnalysis(app,store);
  const autoTags=await registerConversationAutoTags(app,store);
  const tasks=await registerTasks(app,store);
  const afterHttp=await registerAfterHttp(app,store);
  await registerConversationReplies(app,store);
  await registerContactImport(app,store);
  await registerKnowledge(app,store);
  await registerNumbers(app,store);
  await registerIngestion(app,store);
  await registerMembers(app,store);
  registerMetaEmbeddedSignup(app,store);
  registerRecordings(app,store);
  await registerProviders(app,store);
  await registerOAuth(app,store);
  await registerCalendly(app,store);
  await registerIntegrations(app,store);
  await registerEmailAgents(app,store);
  const emailAutomation=await registerEmailAutomation(app,store,{startWorker:options.workers===true});
  await registerScheduling(app,store,{workers:options.workers});
  await registerPublicBooking(app,store);
  await registerPublicBookingUI(app);
  await registerPublicChat(app,store);
  await registerLocalConfig(app,store);
  await registerOps(app);
  await registerBillingUI(app);
  let worker:ReturnType<typeof startWorkers>|undefined;
  let knowledgeBackfill:ReturnType<typeof startKnowledgeBackfill>|undefined;
  app.addHook('onReady',async()=>{if(options.workers){ensureJoanaWhatsAppChannel(store);worker=startWorkers(store);setWhatsAppSchedulerRunning(store,true);crmCapture.start();analysis.start();autoTags.start();tasks.start();afterHttp.start();knowledgeBackfill=startKnowledgeBackfill(store);}});
  app.addHook('onClose',async()=>{await crmCapture.stop();await recovery.stop();await emailAutomation.stop();await worker?.stop();await knowledgeBackfill?.stop();setWhatsAppSchedulerRunning(store,false);});
  registerCallMe(app);
  await registerReferralCodes(app, store);
  await registerSiteLeads(app, store);
  registerPhoneRuntime(app, store);
  registerGoogleCalendarSetup(app);
  registerDemoBooking(app);
  registerSitePreview(app);
  registerStaticWeb(app);
  return app;
}
